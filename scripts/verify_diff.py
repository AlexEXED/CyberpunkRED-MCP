def normalize(s):
    """规范化空值：空格和空字符串等价"""
    if s is None or str(s).strip() == "" or str(s) == " ":
        return ""
    return str(s)

def compare_record(src, rec, name_field, skip_fields=None):
    """逐字段比对，返回差异列表"""
    diffs = []
    skip = skip_fields or ["特殊属性", "数据来源"]  # 特殊属性空值变空格，数据来源变option
    for k, v in rec.items():
        if k in skip:
            continue
        src_v = normalize(src.get(k))
        rec_v = normalize(v)
        if src_v != rec_v:
            diffs.append(f"  [{name_field}] {k}: 源='{src.get(k)}' vs 云端='{v}'")
    return diffs

